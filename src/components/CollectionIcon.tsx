export function CollectionIcon({ icon: name, size = 24, ...props }: Omit<Props, 'name'> & { icon: string | null | undefined }) {
  const drawn: CollectionIconName = isCollectionIcon(name) ? name : DEFAULT_COLLECTION_ICON
  const Shared = SHARED[drawn]
  if (Shared) return <Shared size={size} {...props} />
  return (
    <Svg size={size} {...props}>
      {DRAWN[drawn]}
    </Svg>
  )
}
